def resolve_court_case(addr: str, raw_text: str) -> Tuple[Optional[str], Optional[str]]:
    """
    주소 및 비고란 텍스트를 기반으로 실제 법원 사건번호(YYYY타경XXXXX)와 관할법원을 정밀 탐색합니다.
    1) 텍스트 내 정규식 패턴(202X타경XXXX) 우선 탐색
    2) 실물 PF 매각 대조 맵(KNOWN_COURT_CASES) 매칭
    """
    # 1. 텍스트 내 명시적 타경 번호 추출
    m = re.search(r'(\d{4}\s*타경\s*\d+)', f"{raw_text} {addr}")
    if m:
        case_no = m.group(1).replace(" ", "")
        m_court = re.search(r'([가-힣]+(?:지방법원|지법)(?:\s*[가-힣]+지원)?)', raw_text)
        court = m_court.group(1).replace("지법", "지방법원") if m_court else None
        return case_no, court

    # 2. 주소 기반 실물 경매 매칭 맵 확인
    for key, info in KNOWN_COURT_CASES.items():
        if key in addr or key in raw_text:
            return info["case_no"], info["court"]

    return None, None
